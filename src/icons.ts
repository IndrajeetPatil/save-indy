type IconName = keyof typeof ICON_PATHS;

const SVG_NS = "http://www.w3.org/2000/svg";
const VIEW_BOX = "0 0 16 16";

const isIconName = (value: string): value is IconName =>
  Object.hasOwn(ICON_PATHS, value);

/**
 * Build a decorative inline SVG icon; the control around it carries the name.
 * @param root Document that owns the icon.
 * @param name Which icon to draw.
 * @returns An `<svg>` hidden from assistive technology.
 */
function makeIcon(root: Document, name: IconName): SVGSVGElement {
  const svg = root.createElementNS(SVG_NS, "svg");
  svg.setAttribute("viewBox", VIEW_BOX);
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("focusable", "false");
  svg.classList.add("icon");
  for (const data of ICON_PATHS[name]) {
    const path = root.createElementNS(SVG_NS, "path");
    path.setAttribute("d", data);
    svg.append(path);
  }
  return svg;
}

/**
 * Render an icon as SVG markup, for inlining into the page at build time so
 * it is in place before any script runs.
 * @param name Which icon to draw; unknown names yield `undefined`.
 * @returns The `<svg>` markup.
 */
function iconMarkup(name: string): string | undefined {
  if (!isIconName(name)) {
    return undefined;
  }
  const paths = ICON_PATHS[name].map((data) => `<path d="${data}"></path>`);
  return `<svg class="icon" viewBox="${VIEW_BOX}" aria-hidden="true" focusable="false">${paths.join("")}</svg>`;
}

/**
 * Replace every `<span data-icon="name">` placeholder in the page with its icon.
 * @param root Document to fill.
 */
function fillIcons(root: Document): void {
  for (const slot of root.querySelectorAll<HTMLElement>("[data-icon]")) {
    const name = slot.dataset["icon"] ?? "";
    if (isIconName(name)) {
      slot.replaceWith(makeIcon(root, name));
    }
  }
}

/**
 * Build an icon followed by text, with optional text only screen readers hear.
 * @param root Document that owns the nodes.
 * @param parts The icon, the spoken-only text, and the visible text.
 * @param parts.icon Which icon to show.
 * @param parts.hidden Text for screen readers only.
 * @param parts.text Visible text; backtick spans render as code.
 * @returns The nodes, in reading order.
 */
function iconText(
  root: Document,
  parts: {
    readonly icon: IconName;
    readonly hidden?: string;
    readonly text: string;
  },
): Node[] {
  const nodes: Node[] = [makeIcon(root, parts.icon)];
  if (parts.hidden !== undefined) {
    const hidden = make(root, "span", "visually-hidden");
    hidden.textContent = parts.hidden;
    nodes.push(hidden);
  }
  const text = make(root, "span", "icon-text");
  setRichText(text, parts.text);
  nodes.push(text);
  return nodes;
}

export type { IconName };
export { fillIcons, iconMarkup, iconText, makeIcon };
